-- Event store: strumień zdarzeń per karta (stream_id = numer karty), tylko dopisywanie (append-only).
-- Klucz (stream_id, version) gwarantuje optimistic concurrency: dwóch piszących z tą samą
-- oczekiwaną wersją nie dopisze zdarzenia o tym samym numerze.
create table if not exists card_events
(
    stream_id   varchar(19)              not null,
    version     bigint                   not null,
    type        varchar(64)              not null,
    payload     varchar(4000)            not null,
    occurred_at timestamp with time zone not null,
    position    bigint generated by default as identity,
    primary key (stream_id, version)
);

-- Migawki stanu agregatu - optymalizacja odczytu, zawsze można je skasować
create table if not exists card_snapshots
(
    stream_id varchar(19)   not null primary key,
    version   bigint        not null,
    payload   varchar(4000) not null
);
